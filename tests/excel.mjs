const livro=new ExcelJS.Workbook();await livro.xlsx.load(buffer);
assert.equal(livro.worksheets.length,1);
const folha=livro.worksheets[0];
assert.deepEqual(folha.getRow(1).values.slice(1),['Data','NF','Resistência (MPa)','Local','Volume (m³)','Volume teórico (m³)','7 dias R1','7 dias R2','28 dias R1','28 dias R2','63 dias R1','63 dias R2']);
assert.equal(folha.getCell('B2').value,'00123');
assert.equal(folha.getCell('C2').value,30);assert.equal(folha.getCell('E2').value,8.5);
assert.equal(folha.getCell('F2').value,null);
assert.equal(folha.getCell('F3').value,null);
assert.equal(folha.getCell('F4').value,20);
assert.equal(folha.getCell('G2').value,0,'Zero não vira vazio');
assert.equal(folha.getCell('H2').value,null);
assert.equal(folha.getCell('K2').value,'Opcional');
assert.equal(folha.getCell('G3').value,'Não necessário');
assert.equal(folha.getCell('B3').value,'=1+1');assert.equal(folha.getCell('B3').type,ExcelJS.ValueType.String,'Texto de NF não pode virar fórmula');
assert.equal(folha.getCell('A2').value.toISOString().slice(0,10),'2026-10-12');
